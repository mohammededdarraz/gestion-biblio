/**
 * Generate 2 to 3 physical copies for each of the 48 computer science books.
 * Several books will have ALL copies borrowed so they show up as "Ouvrages en souffrance":
 * - LIV-CS-001 (Clean Code): 3 copies, all 3 borrowed!
 * - LIV-CS-010 (Head First Java): 2 copies, all 2 borrowed!
 * - LIV-CS-019 (React 18 Patterns): 2 copies, all 2 borrowed!
 * - LIV-CS-023 (Spring in Action): 2 copies, all 2 borrowed!
 * - LIV-CS-025 (Designing Data-Intensive Applications): 3 copies, all 3 borrowed!
 * - LIV-CS-032 (CLRS Introduction to Algorithms): 3 copies, all 3 borrowed!
 * - LIV-CS-042 (Artificial Intelligence Russell & Norvig): 3 copies, all 3 borrowed!
 * - LIV-CS-045 (Docker Deep Dive): 3 copies, all 3 borrowed!
 */
export function generateSeedCopies(): PhysicalCopy[] {
  const copies: PhysicalCopy[] = [];
  const souffranceBookIds = new Set([
    'LIV-CS-001',
    'LIV-CS-010',
    'LIV-CS-019',
    'LIV-CS-023',
    'LIV-CS-025',
    'LIV-CS-032',
    'LIV-CS-042',
    'LIV-CS-045',
  ]);

  SEED_BOOKS_RAW.forEach((book, idx) => {
    const isSouffrance = souffranceBookIds.has(book.id);
    const copyCount = (idx % 3 === 0 || isSouffrance) ? 3 : 2;

    for (let i = 1; i <= copyCount; i++) {
      const copyNumStr = String(i).padStart(2, '0');
      const copyId = `EX-${book.isbn.slice(-8)}-${copyNumStr}`;
      const barcode = `BC-${String(idx + 1).padStart(3, '0')}${copyNumStr}`;

      let status: 'available' | 'borrowed' = 'available';
      if (isSouffrance) {
        status = 'borrowed'; // ALL copies borrowed!
      } else if (i === copyCount && (idx % 2 === 0)) {
        status = 'borrowed'; // 1 copy borrowed out of 2 or 3
      }

      copies.push({
        id: copyId,
        barcode,
        bookId: book.id,
        status,
        condition: i === 1 ? 'Neuf' : i === 2 ? 'Très bon état' : 'Bon état',
        shelfLocation: book.shelfLocation || 'Rayon Informatique',
        acquiredDate: '2026-01-15',
        notes: 'Données de démonstration pédagogique',
      });
    }
  });

  return copies;
}

